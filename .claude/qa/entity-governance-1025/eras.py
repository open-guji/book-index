"""刻本年代解析：把「清光緒二十三年刻」「康熙間」「民國三年鉛印」等译为公历年（只覆盖明、清、民国年号；其余返回空）。"""
import re
ERAS = {'洪武':1368,'建文':1399,'永樂':1403,'洪熙':1425,'宣德':1426,'正統':1436,'景泰':1450,'天順':1457,'成化':1465,'弘治':1488,'正德':1506,'嘉靖':1522,
        '隆慶':1567,'萬曆':1573,'泰昌':1620,'天啟':1621,'崇禎':1628,'順治':1644,'康熙':1662,'雍正':1723,'乾隆':1736,'嘉慶':1796,'道光':1821,'咸豐':1851,
        '同治':1862,'光緒':1875,'宣統':1909,'民國':1912}
ALIAS = {'万历':'萬曆','隆庆':'隆慶','天启':'天啟','崇祯':'崇禎','顺治':'順治','嘉庆':'嘉慶','咸丰':'咸豐','光绪':'光緒','宣统':'宣統','民国':'民國','永乐':'永樂','正统':'正統','天顺':'天順','嘉靖':'嘉靖','成化':'成化','弘治':'弘治','雍正':'雍正','乾隆':'乾隆','道光':'道光','同治':'同治','康熙':'康熙','洪武':'洪武','洪熙':'洪熙','宣德':'宣德','景泰':'景泰','正德':'正德','建文':'建文','泰昌':'泰昌','豐':'豐','咸豊':'咸豐'}
CN = {'元':1,'〇':0,'零':0,'一':1,'二':2,'三':3,'四':4,'五':5,'六':6,'七':7,'八':8,'九':9}
def cn(s):
    if s == '元': return 1
    if '十' in s:
        a, b = s.split('十'); return (CN.get(a, 1) if a else 1) * 10 + (CN.get(b, 0) if b else 0)
    n = 0
    for ch in s:
        if ch not in CN: return None
        n = n * 10 + CN[ch]
    return n
for k, v in ALIAS.items():
    if k not in ERAS and v in ERAS: ERAS[k] = ERAS[v]
PAT = re.compile('(' + '|'.join(sorted(ERAS, key=len, reverse=True)) + r')(?:([元〇零一二三四五六七八九十]{1,3})年)?')
def years(text):
    out = []
    for m in PAT.finditer(text or ''):
        era, n = m.group(1), m.group(2)
        if n:
            k = cn(n)
            if k: out.append(ERAS[era] + k - 1)
        else:
            out.append(ERAS[era])           # 「康熙間」只取年号起年（偏早，偏宽松）
    out += [int(x) for x in re.findall(r'(?<!\d)(1[4-9]\d\d)(?!\d)', text or '')]
    return out
