import re
ORDER=['上古','先秦','周','春秋','戰國','秦','漢','三國','晉','南北朝','隋','唐','五代','宋','遼','金','元','明','清','民國']
def coarse(d):
    if not d: return None
    d=d.replace('张','張')
    for k,v in [('南北朝','南北朝'),('南朝','南北朝'),('北朝','南北朝'),('北魏','南北朝'),('東魏','南北朝'),('西魏','南北朝'),('北齊','南北朝'),('北周','南北朝'),('劉宋','南北朝'),('蕭梁','南北朝'),('五代','五代'),('後唐','五代'),('後晉','五代'),('後漢','五代'),('後周','五代'),('後梁','五代'),('南唐','五代'),('吳越','五代'),('前蜀','五代'),('後蜀','五代'),('十國','五代'),('西漢','漢'),('東漢','漢'),('兩漢','漢'),('前漢','漢'),('後漢','漢'),('三國','三國'),('魏','三國'),('蜀','三國'),('吳','三國'),('西晉','晉'),('東晉','晉'),('晉','晉'),('北宋','宋'),('南宋','宋'),('宋','宋'),('遼','遼'),('金','金'),('元','元'),('明','明'),('清','清'),('民國','民國'),('隋','隋'),('唐','唐'),('秦','秦'),('漢','漢'),('周','周'),('春秋','春秋'),('戰國','戰國'),('先秦','先秦')]:
        if d.startswith(k): return v
    return d
def idx(c):
    try: return ORDER.index(c)
    except ValueError: return None
def rel(a,b):
    ca,cb=coarse(a),coarse(b)
    if ca is None or cb is None: return 'unk'
    if ca==cb: return 'same'
    ia,ib=idx(ca),idx(cb)
    if ia is None or ib is None: return 'incompat'
    return 'adj' if abs(ia-ib)==1 else 'incompat'
