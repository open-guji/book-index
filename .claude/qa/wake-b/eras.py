NUM = {'元':1,'一':1,'二':2,'三':3,'四':4,'五':5,'六':6,'七':7,'八':8,'九':9,'十':10,'〇':0,'廿':20}
def cn2int(s):
    s=s.strip()
    if s.isdigit(): return int(s)
    if s=='元': return 1
    if '十' in s:
        a,b=s.split('十'); a=NUM.get(a,1) if a else 1; return a*10+(NUM.get(b,0) if b else 0)
    v=0
    for c in s: v=v*10+NUM.get(c,0)
    return v
def era_year(text):
    m=re.search('('+'|'.join(sorted(ERA,key=len,reverse=True))+r')(?:[甲乙丙丁戊己庚辛壬癸][子丑寅卯辰巳午未申酉戌亥])?[（(]?([元〇一二三四五六七八九十廿\d]+)年?',text)
    if m:
        return ERA[m.group(1)]+cn2int(m.group(2))-1, m.group(1)
    m=re.search(r'[（(\[]?(1[5-9]\d\d)',text)
    if m: return int(m.group(1)),None
    return None,None
