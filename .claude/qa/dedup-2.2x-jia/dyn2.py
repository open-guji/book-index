def coarse(d):
    if not d: return None
    d=d.split(';')[0].strip()
    for k,v in MAP:
        if d.startswith(k): return v
    return '?'+d
def _set(c):
    out=set()
    for x in c.split('|'):
        if x=='宋?': out|={'宋','南北朝'}
        elif x=='南北朝?': out|={'南北朝','五代'}
        else: out.add(x)
    return out
def rel(a,b):
    ca,cb=coarse(a),coarse(b)
    if ca is None or cb is None: return 'unk'
    if ca.startswith('?') or cb.startswith('?'): return 'unk'
    sa,sb=_set(ca),_set(cb)
    if sa&sb: return 'same' if len(sa)==len(sb)==1 else 'amb'
    ia=[POS[x] for x in sa]; ib=[POS[x] for x in sb]
    return 'adj' if min(abs(x-y) for x in ia for y in ib)==1 else 'incompat'
