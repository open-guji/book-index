NDLB = 'https://ndlsearch.ndl.go.jp/books/'; CINII = 'https://ci.nii.ac.jp/ncid/'
NDLINST = '國立國會圖書館'
NEW = []
def url(r): return (NDLB if r.startswith('R1') or r.startswith('R0') else CINII) + r
def nm(r): return ('NDL Search ' if r.startswith('R1') or r.startswith('R0') else 'CiNii Books ') + r
def N(work, title, edition, reign, year, hold, desc, basis, text=None, etype='刻本'):
    dt = {'era': '日本', 'reign': reign, 'year': year, 'certainty': 'attested', 'source': 'catalog', 'basis': basis}
    if text: dt['text'] = text
    provs = [(i, c, nm(r) + ' ' + url(r)) for i, c, r in hold]
    srcs = []; seen = set()
    for i, c, r in hold:
        if r in seen: continue
        seen.add(r); srcs.append(('ndl-' + r if r.startswith('R') else 'ncid-' + r, nm(r), url(r)))
    NEW.append((work, title, edition, etype, dt, provs, srcs, desc))
