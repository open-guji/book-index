def verdict(p):
    a,b=W[p['a']],W[p['b']]
    k=p['key']
    for key in [(k,p['a'][-4:],p['b'][-4:]),(k,p['b'][-4:],p['a'][-4:]),k]:
        if key in O and O[key]: return O[key]
    ca,cb=a['col'],b['col']
    if any(x in ca+cb for x in DUNHUANG): return ('D','敦煌遺書（不碰名單），不判')
    if (LEISHUO in ca)!=(LEISHUO in cb): return ('D','類說為曾慥摘錄本，與全本同否待核')
    if any(x in ca for x in YUSHAN) and any(x in cb for x in YUSHAN) and not p['jconf'] and p['acat'] in ('同','缺'):
        return ('B','虞山地方鈔本系（海虞雜志／虞陽說苑／素心書屋叢鈔等）互相傳鈔，同題同卷')
    wa,wb=wei(ca),wei(cb)
    names=set(p['aa'][0])|set(p['ab'][0])
    if wa and wb and (names&{'孫瑴','喬松年','黃奭'} or {wa,wb}&{'喬松年','黃奭'}):
        return ('A','緯書同一輯本（%s）'%wa) if wa==wb else ('C','緯書異輯（%s／%s）'%(wa,wb))
    fa,fb=fam(ca),fam(cb)
    jok=not p['jconf']
    if k in GENERIC: return ('D','泛稱題名，待核')
    if fa and fa==fb and jok and p['acat'] in ('同','缺'):
        return ('A','同源叢書（%s）異版次'%fa)
    if p['acat']=='同' and jok:
        why='同撰人（%s）'%('、'.join(sorted(set(p['aa'][0])&set(p['ab'][0]))))
        if p['hx']: why+='；總目互見'
        return ('A',why+('，卷數同' if p['jsame'] else '，卷數一側缺'))
    if p['acat']=='缺' and jok:
        if p['hx']: return ('B','總目互見，一側缺撰人')
        if p['yy']: return ('B','影印／據本關係，一側缺撰人')
        if (fa and fb and fa=='說郛系') or ('說郛' in ca+cb and any(x in ca+cb for x in ['古今說部叢書','香豔叢書','說林'])): return ('B?','說郛本與據說郛排印／傳鈔之本，同題（待逐條核）')
        if p['jsame']: return ('B?','同題同卷、一側或兩側缺撰人，無矛盾（待逐條核）')
        return ('D','一側缺撰人且卷數不明，待核')
    return ('D','規則未覆蓋：%s %s'%(p['acat'],'卷矛盾' if p['jconf'] else ''))
